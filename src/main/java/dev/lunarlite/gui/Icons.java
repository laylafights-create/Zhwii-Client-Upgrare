    /** Đổi 8 dòng chữ thành số 64 bit rồi lưu lại theo id. */
    private static void put(String id, String... rows) {
        long bits = 0L;
        for (int r = 0; r < 8; r++) {
            for (int c = 0; c < 8; c++) {
                if (rows[r].charAt(c) == '#') bits |= 1L << (r * 8 + c);
            }
        }
        MAP.put(id, Long.valueOf(bits));
    }

